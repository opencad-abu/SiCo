                "rceInpCB(form)",
                "rceOutTypeCB(form)",
                "form~>createNetlistView~>value=t",
                "form~>reductionEnable~>value=t",
                "rceReductionCB(form)",
                # Non-OA native-view output has no implicit OA destination.
                # Both fields must be editable, and either field must keep the
                # complete lib/cell/view target synchronized.
                'form~>outType~>value="view"',
                "rceOutTypeCB(form)",
                'form~>inpType~>value="CDL+GDS"',
