                "  form~>reductionSelectionFile~>invisible)",
                'form~>reductionMode~>value="Delay and Frequency"',
                "rceReductionModeCB(form)",
                "delayGeometryOk=and(!form~>reductionDelayRelPrompt~>invisible",
                "  !form~>reductionDelayAbsPrompt~>invisible",
                "  !form~>reductionFrequencyPrompt~>invisible)",
                "delayRelInfo=hiGetFieldInfo(form 'reductionDelayRel)",
                "delayAbsInfo=hiGetFieldInfo(form 'reductionDelayAbs)",
                "frequencyInfo=hiGetFieldInfo(form 'reductionFrequency)",
