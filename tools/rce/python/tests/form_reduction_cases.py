                f'form~>cdlRunDirectory~>value={_skill_literal(tmp_path)}',
                "cdlDirectoryValidationOk=and(cdlDirectoryValidationOk",
                "  !rceValidateCdlRunDirectory(form))",
                f'cdlEnv=outfile({_skill_literal(tmp_path / "si.env")})',
                'fprintf(cdlEnv "simulator = auCdl\\n")',
                "close(cdlEnv)",
