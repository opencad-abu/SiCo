                "reductionOnlyOk=and(!form~>createNetlistView~>value",
                "  form~>reductionEnable~>value)",
                "form~>reductionEnable~>value=nil",
                "rceReductionCB(form)",
                "bothDisabledOk=and(!form~>createNetlistView~>value",
                "  !form~>reductionEnable~>value)",
                "initialOk=and(form form~>reductionEnable form~>reductionMode",
                "  form~>reductionOutputTag form~>reductionControl",
                "  form~>reductionDelayRel form~>reductionDelayAbs",
                "  form~>reductionFrequency form~>reductionSelectionFile",
                "  form~>reductionTemperature form~>reductionGround",
                "  form~>reductionNegative form~>reductionCanonicalDeviceFile",
