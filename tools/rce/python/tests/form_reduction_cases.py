                '  caddr(rceNativeViewTarget(form))=="smart_view_custom")',
                'form~>inpType~>value="OA"',
                "rceInpCB(form)",
                "oaTargetStateOk=and(!form~>viewTarget~>editable",
                "  form~>viewName~>editable form~>viewName~>enabled)",
                'form~>outType~>value="dspf"',
                "rceOutTypeCB(form)",
                # Returning from the native-view capability check should not
                # implicitly restore a cleared user choice; select it again
                # explicitly before testing reduction-mode transitions.
                "form~>createNetlistView~>value=t",
                "singleCornerOk=and(form~>reductionEnable~>enabled",
                "  form~>reductionEnable~>value",
                "  !form~>reductionOptions~>invisible)",
                'form~>cornerType~>value="Multiple Corners"',
                "rceCornerTypeCB(form)",
                "multiCornerOk=and(!form~>reductionEnable~>enabled",
                "  !form~>reductionEnable~>value",
                "  form~>reductionOptions~>invisible)",
                'form~>cornerType~>value="Single Corner"',
                "rceCornerTypeCB(form)",
                "restoredSingleCornerOk=and(form~>reductionEnable~>enabled",
                "  !form~>reductionEnable~>value",
                "  form~>reductionOptions~>invisible)",
                # Continue the capability checks with Reduction explicitly
                # re-enabled; returning to Single Corner must not restore the
                # checked state implicitly.
                "form~>reductionEnable~>value=t",
                "rceReductionCB(form)",
                "promptGeometryOk=and(form~>reductionModePrompt~>invisible==nil",
                "  form~>reductionOutputTagPrompt~>invisible==nil",
                "  form~>reductionControlPrompt~>invisible",
                "  form~>reductionDelayRelPrompt~>invisible",
                "  form~>reductionDelayAbsPrompt~>invisible",
                "  form~>reductionFrequencyPrompt~>invisible)",
                "defaultOk=and(form~>reductionEnable~>enabled==t",
                "  !form~>reductionOptions~>invisible",
                "  form~>reductionControl~>invisible",
                "  form~>reductionDelayRel~>invisible",
                "  form~>reductionDelayAbs~>invisible",
                "  form~>reductionFrequency~>invisible",
                "  form~>reductionSelectionFile~>invisible",
                "  !form~>reductionTemperature~>invisible",
                "  form~>reductionCanonicalDeviceFile~>invisible)",
                'form~>reductionMode~>value="Reduction Control"',
                "rceReductionModeCB(form)",
                "controlOk=and(!form~>reductionControl~>invisible",
                "  form~>reductionDelayRel~>invisible",
                "  form~>reductionDelayAbs~>invisible",
