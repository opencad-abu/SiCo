"""Calibre xACT (``CalXACT``) cases for the shared Calibre PEX flow."""

from __future__ import annotations

import sys
from pathlib import Path

import pytest

PYTHON_ROOT = Path(__file__).resolve().parents[1]
if str(PYTHON_ROOT) not in sys.path:
    sys.path.insert(0, str(PYTHON_ROOT))

from rcepy.generators import generate_all  # noqa: E402
from rcepy.runner import RceRunner  # noqa: E402
from xrc_test_support import (  # noqa: E402
    install_fake_calibre,
    make_xrc_config,
    xrc_stages,
)


@pytest.mark.parametrize(
    ("rc_type", "pdb_prefix", "fmt_switches"),
    [
        ("RCC", ("-xact", "-3d", "-pdb", "-rcc"), ("-all",)),
        ("R+Cg", ("-xact", "-3d", "-pdb", "-rc"), ("-all",)),
        ("R", ("-xact", "-r"), ("-r",)),
        ("Cg+Cc", ("-xact", "-3d", "-pdb", "-rc"), ("-c",)),
        ("Cg", ("-xact", "-3d", "-pdb", "-rc"), ("-c", "-g")),
    ],
)
def test_xact_rc_mode_selects_engine_pdb_and_formatter_flags(
    tmp_path: Path,
    monkeypatch: pytest.MonkeyPatch,
    rc_type: str,
    pdb_prefix: tuple[str, ...],
    fmt_switches: tuple[str, ...],
) -> None:
    cfg, _ = make_xrc_config(tmp_path, rc_type=rc_type, tool="CalXACT")
    calibre = install_fake_calibre(tmp_path / "mgc")
    monkeypatch.setenv("MGC_HOME", str(calibre.parents[1]))

    stages = {stage.name: stage for stage in xrc_stages(cfg)}

    # xACT runs resistance-only extraction as a standalone mode; every other
    # parasitic model needs the 3D PDB (``-3d -pdb``) invocation.
    pdb = stages["xrc_pdb"].command
    fmt = stages["xrc_fmt"].command
    assert tuple(pdb[1 : 1 + len(pdb_prefix)]) == pdb_prefix
    assert tuple(fmt[1:3]) == ("-xact", "-fmt")
    assert tuple(fmt[3 : 3 + len(fmt_switches)]) == fmt_switches


def test_xact_control_file_declares_the_xact_svdb_query(
    tmp_path: Path,
) -> None:
    cfg, paths = make_xrc_config(tmp_path, tool="CalXACT")

    generate_all(cfg, cfg.context())
    text = paths["runset"].read_text(encoding="utf-8")

    assert "// Calibre xACT control file generated by rcepy." in text
    assert f'MASK SVDB DIRECTORY "{paths["svdb"]}" QUERY XACT' in text
    assert "QUERY XRC" not in text
    # The conversion stage stays on the shared LVS command for both engines.
    assert [stage.name for stage in xrc_stages(cfg)] == [
        "xrc_lvs",
        "xrc_pdb",
        "xrc_fmt",
    ]
    assert xrc_stages(cfg)[0].command[1:4] == ["-lvs", "-hier", "-spice"]


def test_mock_calibre_xact_runs_serially_and_creates_artifacts(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    cfg, paths = make_xrc_config(tmp_path, tool="CalXACT")
    calibre = install_fake_calibre(tmp_path / "mgc")
    trace = tmp_path / "calibre.trace"
    monkeypatch.setenv("MGC_HOME", str(calibre.parents[1]))
    monkeypatch.setenv("FAKE_CALIBRE_TRACE", str(trace))

    assert RceRunner(cfg).run() == 0

    commands = trace.read_text(encoding="utf-8").splitlines()
    assert len(commands) == 3
    assert commands[1].startswith("-xact -3d -pdb -rcc -turbo 3 -nowait")
    assert commands[2].startswith("-xact -fmt -all -nowait")
    assert paths["output"].is_file()
    assert not (paths["run_dir"] / "log" / "exit-abnormally").exists()


def test_xact_transcript_errors_stop_the_flow(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    cfg, paths = make_xrc_config(tmp_path, tool="CalXACT")
    calibre = install_fake_calibre(tmp_path / "mgc")
    trace = tmp_path / "calibre.trace"
    monkeypatch.setenv("MGC_HOME", str(calibre.parents[1]))
    monkeypatch.setenv("FAKE_CALIBRE_TRACE", str(trace))
    monkeypatch.setenv("FAKE_PDB_XACT_ERRORS", "1")

    with pytest.raises(RuntimeError, match="Calibre xACT reported errors"):
        RceRunner(cfg).run()

    commands = trace.read_text(encoding="utf-8").splitlines()
    assert len(commands) == 2


def test_xact_include_nets_use_the_select_switch(tmp_path: Path) -> None:
    cfg, _ = make_xrc_config(tmp_path, tool="CalXACT")
    cfg = cfg.replace(
        "selection",
        value={
            "net_enable": True,
            "net_type": "Include Nets",
            "nets": ["VDD", "X1/OUT"],
        },
    )

    pdb = xrc_stages(cfg)[1].command

    # -cselect belongs to the xRC PDB flow only.
    assert "-select" in pdb
    assert "-cselect" not in pdb
    assert "-xcell" not in pdb
    cfg = cfg.replace("extract", "rc_type", value="Cg")
    pdb = xrc_stages(cfg)[1].command
    assert "-select" in pdb
    assert "-cselect" not in pdb


def test_xact_request_is_recognized_as_the_calibre_pex_flow(
    tmp_path: Path,
) -> None:
    cfg, _ = make_xrc_config(tmp_path, tool="CalXACT")

    assert cfg.is_calibre_pex
    assert cfg.ext_tool == "CalXACT"
    assert [stage.name for stage in xrc_stages(cfg)][0] == "xrc_lvs"


def test_xact_rejects_rc_types_outside_the_calibre_pex_contract(
    tmp_path: Path,
) -> None:
    cfg, _ = make_xrc_config(tmp_path, rc_type="Totem", tool="CalXACT")

    with pytest.raises(ValueError, match="Unsupported Calibre PEX RC type"):
        generate_all(cfg, cfg.context())
