"""Generate deterministic source entries; never a runtime/release fallback."""

from __future__ import annotations

import argparse
import json
import os
from pathlib import Path
import textwrap

if __package__:
    from .skill_loader_contract import KERNEL, MANIFEST, classes, contract, manifest, members
else:
    from skill_loader_contract import KERNEL, MANIFEST, classes, contract, manifest, members

ROOT = Path(__file__).resolve().parents[2]
MARKERS = {"assistant": "aiLoaderVersion", "sico": "sicoLoaderVersion",
           "ai_shared": "aiSharedLoaderVersion"}


def prelude(name):
    if name in {"assistant", "sico"}:
        module = "ai" if name == "assistant" else "sico"
        return [f'  set(\'{module}Root strcat(SICO_sourceRoot() "/tools/{module}"))']
    if name in {"drc", "lvs", "rce", "lef"}:
        return [f'  {name}{suffix}=strcat(SICO_sourceRoot() "{path}")'
                for suffix, path in [("ToolsRoot", "/tools"), ("SkillRoot", f"/tools/{name}"),
                                     ("CommonRoot", "/tools/common"), ("UtilityRoot", "/tools/utility")]]
    return []


def render(root, name, groups=None):
    groups = manifest(root) if groups is None else groups
    group = groups[name]
    fingerprint, rows = contract(root, group)
    output = Path(group["output"])
    kernel = os.path.relpath(KERNEL, output.parent)
    marker = MARKERS.get(name)
    lines = ["; Generated by tools/utility/skill_loader.py --write; edit the manifest/sources.",
             "; Source-only. Per-file contracts retain successful members across retries."]
    if marker:
        lines.append(f"set('{marker} nil)")
    lines.extend(["let((entryDirectory)",
                  '  entryDirectory=strcat("/" buildString(reverse(cdr(reverse(',
                  '    parseString(simplifyFilename(get_filename(piport) t) "/")))) "/"))',
                  f'  load(strcat(entryDirectory "/{kernel}"))'])
    for dependency in group["requires"]:
        relative = os.path.relpath(groups[dependency]["output"], output.parent)
        lines.append(f'  load(strcat(entryDirectory "/{relative}"))')
    lines.extend(prelude(name))
    lines.append(f'  SICO_sourceRequire("{name}" "{fingerprint}" \'(')
    for path, digest, exports, revisions, guards in rows:
        location = Path(path)
        lines.append(f'    ("{location.parent}" "{location.name}" "{digest}"')
        fields = ["(" + " ".join(exports) + ")",
                  "(" + " ".join(f"({fun} {json.dumps(value)})" for fun, value in revisions) + ")",
                  "(" + " ".join(guards) + ")",
                  "(" + " ".join(classes((root / path).read_text())) + "))"]
        for field in fields:
            lines.extend(textwrap.wrap(field, width=105, initial_indent="      ",
                                       subsequent_indent="       ", break_long_words=False,
                                       break_on_hyphens=False))
    lines.append("  ))")
    if group.get("initialize"):
        lines.append(f'  SICO_sourceInitialize("{name}" \'({" ".join(group["initialize"])}))')
    if marker:
        value = (json.dumps("ai.shared.v5." + fingerprint) if name == "ai_shared"
                 else "aiLoaderRevision()" if name == "assistant" else "sicoLoaderRevision()")
        lines.append(f"  set('{marker} {value})")
    lines.append(")")
    return "\n".join(lines) + "\n"


def check(root=ROOT):
    try:
        groups = manifest(root)
        errors = []
        for name, group in groups.items():
            if (root / group["output"]).read_text() != render(root, name, groups):
                errors.append(f"{group['output']}: stale source loader; run "
                              "python3 tools/utility/skill_loader.py --write")
        return errors
    except (OSError, ValueError, KeyError, TypeError) as exc:
        return [f"invalid source loader contract: {exc}"]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=ROOT)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--check", action="store_true")
    mode.add_argument("--write", action="store_true")
    args = parser.parse_args()
    if args.write:
        groups = manifest(args.root)
        outputs = {group["output"]: render(args.root, name, groups)
                   for name, group in groups.items()}
        for path, text in outputs.items():
            target = args.root / path
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(text)
        return 0
    errors = check(args.root)
    for error in errors:
        print(error)
    return int(bool(errors))


if __name__ == "__main__":
    raise SystemExit(main())
