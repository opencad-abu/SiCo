"""Generate Python and SKILL constants from the JSON DataHub registry."""

from __future__ import annotations

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CONTRACTS = ROOT / "datahub" / "contracts"
LEGACY_ERRORS = ROOT / "datahub" / "legacy_errors.json"
OUTPUT = ROOT / "python" / "sico_datahub" / "contracts.py"
SKILL_OUTPUT = ROOT.parent / "ai" / "skill" / "AI_datahub_contracts.il"
TCL_OUTPUT = ROOT / "tcl" / "datahub_contracts.tcl"
HEADER = '''"""Generated contract/action constants; run datahub/generate_contracts.py."""

'''
SKILL_HEADER = """; Generated by tools/common/datahub/generate_contracts.py.
; Edit contracts/*.json or legacy_errors.json, then regenerate.
"""
TCL_HEADER = """# Generated by tools/common/datahub/generate_contracts.py.
# Edit contracts/*.json or legacy_errors.json, then regenerate.
"""


def _rows():
    values = {}
    for path in sorted(CONTRACTS.glob("*.json")):
        value = json.loads(path.read_text(encoding="utf-8"))
        values[value["name"]] = value
    return values


def _literal(value):
    return repr(value).replace("'", '"')


def _load():
    values = _rows()
    legacy_errors = json.loads(LEGACY_ERRORS.read_text(encoding="utf-8"))
    error_codes = tuple(sorted({
        code
        for value in values.values()
        for code in value["errors"]
    }))
    return values, legacy_errors, error_codes


def render():
    values, legacy_errors, error_codes = _load()
    names = tuple(sorted(values))
    lines = [
        HEADER.rstrip(),
        "",
        "CONTRACTS = " + _literal(names),
        "VERSIONS = " + repr({name: values[name]["version"] for name in names}),
        "ACTIONS = " + repr({
            name: tuple(sorted(values[name]["actions"]))
            for name in names
        }),
        "CAPABILITIES = " + repr({
            name: {
                action: value["capability"]
                for action, value in sorted(values[name]["actions"].items())
            }
            for name in names
        }),
        "RESPONSE_SCHEMAS = " + repr({
            name: {
                action: value["response"]["schema"]
                for action, value in sorted(values[name]["actions"].items())
            }
            for name in names
        }),
        "SCHEMAS = " + repr({
            name: values[name]["schema"]
            for name in names if "schema" in values[name]
        }),
        "ERROR_CODES = " + repr(error_codes),
        "LEGACY_ERRORS = " + repr(legacy_errors),
        "",
    ]
    return "\n".join(lines)


def _skill_list(values, indent=0):
    pad = " " * indent
    if not values:
        return "list()"
    items = [json.dumps(value, ensure_ascii=False) for value in values]
    if sum(map(len, items)) + 2 * len(items) + 7 <= 100:
        return "list(" + " ".join(items) + ")"
    return "list(\n" + "".join(
        f"{pad}  {json.dumps(value, ensure_ascii=False)}\n" for value in values
    ) + pad + ")"


def render_skill():
    values, legacy_errors, _error_codes = _load()
    lines = [SKILL_HEADER, 'datahubContractRevision="20261023.ai.datahub.contracts.v1"',
             "datahubContractRows = list("]
    for name in sorted(values):
        value = values[name]
        limits = value["limits"]
        lines.append(f'  list("{name}" {value["version"]}')
        lines.append("    list(" if value["actions"] else "    list()")
        for action, spec in sorted(value["actions"].items()):
            request = spec["request"]
            lines.append(
                f'      list("{action}" "{spec["capability"]}" '
                f'"{spec["response"]["schema"]}"'
            )
            lines.append(f'        {_skill_list(request["fields"], 8)}')
            lines.append(
                f'        {_skill_list(sorted(value["errors"]), 8)})'
            )
        if value["actions"]:
            lines.append("    )")
        lines.append(
            f'    list({limits["max_items"]} {limits["max_text"]} '
            f'{limits["max_bytes"]}))'
        )
    lines.extend([
        "  )",
        "datahubLegacyErrors = list(",
    ])
    for source, target in sorted(legacy_errors.items()):
        lines.append(f'  list("{source}" "{target}")')
    lines.append(")")
    return "\n".join(lines) + "\n"


def _tcl_string(value):
    return json.dumps(value, ensure_ascii=False)


def _tcl_list(values):
    return "[list " + " ".join(_tcl_string(value) for value in values) + "]"


def render_tcl():
    values, legacy_errors, error_codes = _load()
    lines = [
        TCL_HEADER,
        'set ::datahubContractRevision "20261023.ai.datahub.contracts.v1"',
        "set ::datahubContractRows [list \\",
    ]
    for name in sorted(values):
        value = values[name]
        limits = value["limits"]
        lines.append(
            f'  [list {_tcl_string(name)} {value["version"]} \\'
        )
        lines.append("    [list \\")
        for action, spec in sorted(value["actions"].items()):
            request = spec["request"]
            lines.append(
                f'      [list {_tcl_string(action)} '
                f'{_tcl_string(spec["capability"])} '
                f'{_tcl_string(spec["response"]["schema"])} \\'
            )
            lines.append(
                f'        {_tcl_list(request["fields"])} \\'
            )
            lines.append(
                f'        {_tcl_list(sorted(value["errors"]))}] \\'
            )
        lines.append("    ] \\")
        lines.append(
            f'    [list {limits["max_items"]} {limits["max_text"]} '
            f'{limits["max_bytes"]}]] \\'
        )
    lines.extend([
        "]",
        "set ::datahubErrorCodes " + _tcl_list(error_codes),
        "set ::datahubLegacyErrors [dict create \\",
    ])
    for source, target in sorted(legacy_errors.items()):
        lines.append(
            f'  {_tcl_string(source)} {_tcl_string(target)} \\'
        )
    lines.append("]")
    return "\n".join(lines) + "\n"


def _outputs():
    return (
        (OUTPUT, render()),
        (SKILL_OUTPUT, render_skill()),
        (TCL_OUTPUT, render_tcl()),
    )


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    outputs = _outputs()
    if args.check:
        errors = []
        for path, rendered in outputs:
            current = path.read_text(encoding="utf-8") if path.is_file() else ""
            if current != rendered:
                errors.append(f"generated contracts are stale: {path}")
        if errors:
            print("\n".join(errors))
            return 1
        print("generated Python/SKILL contracts match the JSON registry")
        return 0
    for path, rendered in outputs:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(rendered, encoding="utf-8")
        print(f"wrote {path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
